// Writes apps/web/lib/brand/pay-button-assets.ts: what the Tegata pay button is drawn from, so the button looks the
// same on any merchant's site without a font: Archivo glyph outlines (OFL, @fontsource) for its words and figures,
// the 手形 seal from app/icon.svg (vermilion, and inverted for the vermilion button), and the real coin marks.
// Run: node scripts/brand/pay-button.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import opentype from "opentype.js"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "../..")
const require = createRequire(import.meta.url)

const font = (weight) => {
  const buf = readFileSync(
    require.resolve(`@fontsource/archivo/files/archivo-latin-${weight}-normal.woff`),
  )
  const parsed = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
  // opentype.js misreads one of Archivo's contextual lookups; single glyphs need none.
  parsed.tables.gsub = undefined
  return parsed
}

const n = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(1))
const pathData = (path) =>
  path.commands
    .map((c) =>
      c.type === "M" || c.type === "L"
        ? `${c.type}${n(c.x)} ${n(c.y)}`
        : c.type === "Q"
          ? `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`
          : c.type === "C"
            ? `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`
            : "Z",
    )
    .join("")

const CHARS = "Pay$0123456789.,withTegawl "
/** Each glyph at a 1000-unit size on a baseline at 0: its outline and how far it advances. */
function glyphs(weight) {
  const f = font(weight)
  const out = {}
  for (const ch of CHARS) {
    const glyph = f.charToGlyph(ch)
    out[ch] = {
      d: ch === " " ? "" : pathData(glyph.getPath(0, 0, 1000)),
      w: Math.round((glyph.advanceWidth / f.unitsPerEm) * 1000),
    }
  }
  return out
}

const sealSvg = readFileSync(join(root, "apps/web/app/icon.svg"), "utf8")
const sealInner = sealSvg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")
// The seal on a vermilion button: a white square, vermilion rule and glyphs.
const sealPaper = sealInner
  .replace('fill="#FF4F00"', 'fill="#FFFFFF"')
  .replace('stroke="#fff"', 'stroke="#FF4F00"')
  .replaceAll('fill="#fff"', 'fill="#FF4F00"')

const MARKS = ["usdc", "usdt", "eth", "sol", "btc"]
const marks = Object.fromEntries(
  MARKS.map((id) => [
    id,
    `data:image/svg+xml;base64,${readFileSync(join(root, `apps/web/public/marks/${id}.svg`)).toString("base64")}`,
  ]),
)

const file = `// Generated by scripts/brand/pay-button.mjs from Archivo (OFL, @fontsource), app/icon.svg and public/marks.
// Don't edit by hand: run the script.

/** Archivo glyphs at a 1000-unit size, baseline at 0: outline and advance. */
export const GLYPHS_800: Record<string, { d: string; w: number }> = ${JSON.stringify(glyphs(800))}

export const GLYPHS_900: Record<string, { d: string; w: number }> = ${JSON.stringify(glyphs(900))}

/** The 手形 seal (viewBox 0 0 200 200): vermilion, and inverted for a vermilion button. */
export const SEAL_SHU = ${JSON.stringify(sealInner)}
export const SEAL_PAPER = ${JSON.stringify(sealPaper)}

/** Coin marks as data URLs, in the order the button shows them. */
export const COIN_MARKS: Record<string, string> = ${JSON.stringify(marks)}
`
writeFileSync(join(root, "apps/web/lib/brand/pay-button-assets.ts"), file)
console.log("apps/web/lib/brand/pay-button-assets.ts written")
