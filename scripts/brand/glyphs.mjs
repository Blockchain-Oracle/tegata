// Extracts the outlines of 手 and 形 from OFL Japanese fonts (fontsource) as SVG path data, so the seal ships as
// paths and no Japanese font is ever loaded by the app. Writes apps/web/lib/brand/glyphs.ts.
// Run: node scripts/brand/glyphs.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import opentype from "opentype.js"

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, "../../apps/web/lib/brand/glyphs.ts")

const CHARS = ["手", "形"]
/** The em box every glyph is drawn into (font units are normalised to this). */
const BOX = 1000
const FACES = [
  {
    key: "shippori",
    pkg: "@fontsource/shippori-mincho-b1",
    file: "shippori-mincho-b1",
    weight: 800,
    name: "Shippori Mincho B1 800",
  },
  {
    key: "notoSerif",
    pkg: "@fontsource/noto-serif-jp",
    file: "noto-serif-jp",
    weight: 900,
    name: "Noto Serif JP 900",
  },
]

/** fontsource splits CJK fonts into numbered subsets; find the subset whose unicode-range covers a code point. */
function subsetFor(pkgDir, weight, codePoint) {
  const css = readFileSync(join(pkgDir, `${weight}.css`), "utf8")
  const blocks = css.split("@font-face").slice(1)
  for (const block of blocks) {
    const src = block.match(/files\/([^)]+?-(\d+)-\d+-normal)\.woff2/)
    const range = block.match(/unicode-range:\s*([^;]+);/)
    if (!src || !range) continue
    for (const part of range[1].split(",")) {
      const [lo, hi] = part
        .trim()
        .replace("U+", "")
        .split("-")
        .map((h) => Number.parseInt(h, 16))
      if (codePoint >= lo && codePoint <= (hi ?? lo)) return join(pkgDir, "files", `${src[1]}.woff`)
    }
  }
  throw new Error(`no subset covers U+${codePoint.toString(16)}`)
}

const result = {}
for (const face of FACES) {
  const pkgDir = dirname(require.resolve(`${face.pkg}/package.json`))
  result[face.key] = { name: face.name, glyphs: {} }
  for (const ch of CHARS) {
    const file = subsetFor(pkgDir, face.weight, ch.codePointAt(0))
    const font = opentype.parse(readFileSync(file).buffer.slice(0))
    const scale = BOX / font.unitsPerEm
    const glyph = font.charToGlyph(ch)
    // opentype's y axis points up; draw at baseline = ascender so the glyph sits in a 0..BOX box.
    const path = glyph.getPath(0, font.ascender * scale, BOX)
    const box = path.getBoundingBox()
    result[face.key].glyphs[ch] = {
      d: path.toPathData(2),
      box: [box.x1, box.y1, box.x2, box.y2].map((n) => Math.round(n)),
    }
  }
}

const body = [
  "// GENERATED by scripts/brand/glyphs.mjs from OFL fonts (fontsource). Do not edit; change the script and re-run.",
  "// The 手形 outlines for the Tegata seal, so no Japanese font is ever shipped.",
  `export const GLYPH_BOX = ${BOX}`,
  "",
  `export const SEAL_FACES = ${JSON.stringify(result, null, 2)} as const`,
  "",
  "export type SealFace = keyof typeof SEAL_FACES",
  "",
].join("\n")
writeFileSync(out, body)
console.log(
  "wrote",
  out,
  Object.keys(result).map(
    (k) => `${k}: ${CHARS.map((c) => result[k].glyphs[c].box.join(",")).join(" | ")}`,
  ),
)
