// Embeds the PDF fonts (Archivo and DM Mono, both SIL OFL) as base64 data URLs in packages/documents/src/fonts.ts,
// so PDFs render the same in the web server and the worker with no font files to ship and no network call.
// Run: node scripts/documents/fonts.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const file = (pkg, name) => readFileSync(require.resolve(`${pkg}/files/${name}`)).toString("base64")
const fonts = {
  archivo400: file("@fontsource/archivo", "archivo-latin-400-normal.woff"),
  archivo600: file("@fontsource/archivo", "archivo-latin-600-normal.woff"),
  archivo800: file("@fontsource/archivo", "archivo-latin-800-normal.woff"),
  mono400: file("@fontsource/dm-mono", "dm-mono-latin-400-normal.woff"),
}
const body = Object.entries(fonts)
  .map(([key, b64]) => `export const ${key} = "data:font/woff;base64,${b64}"`)
  .join("\n")
writeFileSync(
  new URL("../../packages/documents/src/fonts.ts", import.meta.url),
  `// Generated by scripts/documents/fonts.mjs from @fontsource (SIL Open Font License). Do not edit.\n${body}\n`,
)
console.log("fonts.ts written:", Object.keys(fonts).join(", "))
